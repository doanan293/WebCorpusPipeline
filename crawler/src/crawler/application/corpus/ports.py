from __future__ import annotations

from collections.abc import Iterable, Iterator
from contextlib import AbstractContextManager
from pathlib import Path
from typing import Any, Protocol

from crawler.domain.corpus.manifest import Fingerprint


class CorpusFiles(Protocol):
    """Reading, writing and swapping in the files of a corpus package."""

    def read_jsonl(self, path: Path) -> Iterator[dict[str, Any]]: ...

    def write_jsonl(self, path: Path, rows: Iterable[dict[str, Any]]) -> int: ...

    def read_json(self, path: Path) -> Any: ...

    def write_json(self, path: Path, value: Any) -> None: ...

    def exists(self, path: Path) -> bool: ...

    def names(self, folder: Path) -> list[str]: ...

    def fingerprint(self, path: Path) -> Fingerprint: ...

    def line_count(self, path: Path) -> int: ...

    def copy(self, source: Path, destination: Path) -> None: ...

    def find(self, folder: Path, name: str) -> list[Path]: ...

    def staging(self, output: Path) -> AbstractContextManager[Path]: ...

    def temporary(self, prefix: str) -> AbstractContextManager[Path]: ...

    def replace(self, staging: Path, output: Path) -> None: ...

    def install_copy(self, folder: Path, destination: Path) -> None: ...


class CorpusDatabase(Protocol):
    """The slide's ``html``, ``other`` and ``graph`` collections."""

    def iter_collection(self, name: str) -> Iterator[dict[str, Any]]: ...

    def load(self, name: str, docs: Iterable[dict[str, Any]]) -> int:
        """Upsert ``docs`` (by ``url``; graph edges by ``src`` and ``dest``); return how many."""
        ...

    def find_edges(
        self, *, src: str | None, dest: str | None, limit: int
    ) -> list[dict[str, Any]]: ...

    def ensure_indexes(self) -> None: ...


class DatasetPublisher(Protocol):
    def create(self, folder: Path) -> None: ...

    def version(self, folder: Path, message: str) -> None: ...

    def download(self, dataset: str, folder: Path) -> None: ...

    def list_files(self, dataset: str) -> list[str]: ...

    def download_file(self, dataset: str, name: str, folder: Path) -> None: ...
